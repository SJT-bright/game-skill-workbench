#!/usr/bin/env python3
"""Build parts-3x/GameUIKit.ts (Cocos Creator 3.x) from parts/GameUIKit.js (2.4) - 生成时预防 A2 批 (P05 3.x).

  python3 -B tools/make_gameuikit_3x.py           # write ../parts-3x/GameUIKit.ts
  python3 -B tools/make_gameuikit_3x.py --check   # exit 1 when GameUIKit.ts is not what the two sources give now

One interface for both engines: the engine-neutral core (between the "GameUIKit core BEGIN / END" lines of
parts/GameUIKit.js) is copied byte for byte; only the engine adapter differs (parts-3x/GameUIKit.adapter-3x.js).
Edit the 2.4 file or the adapter, never GameUIKit.ts, then run this again. Same layout as ad-boost's AdBoostKit.ts
(ad-boost/ui-kit/tools/build_kit.py), so a 3.x game uses it the same way:
  import GameUIKit from '../tiktok-platform/GameUIKit';     // or (globalThis as any).TikTokGameUIKit
"""
import argparse
import re
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
SRC24 = KIT / 'parts' / 'GameUIKit.js'
ADAPTER = KIT / 'parts-3x' / 'GameUIKit.adapter-3x.js'
OUT = KIT / 'parts-3x' / 'GameUIKit.ts'
BEGIN = '// ==== GameUIKit core BEGIN'
END = '// ==== GameUIKit core END ===='


def build():
    src = SRC24.read_text(encoding='utf-8')
    i, j = src.find(BEGIN), src.find(END)
    if i < 0 or j < i:
        raise SystemExit('make_gameuikit_3x: core markers not found in %s' % SRC24)
    core = src[i:j + len(END)]
    ver = re.search(r"version: '([0-9.]+)', kit: 'GameUIKit'", core)
    if not ver:
        raise SystemExit('make_gameuikit_3x: no version in the core')
    adapter = ADAPTER.read_text(encoding='utf-8')
    return ('// GameUIKit %s (Cocos Creator 3.x) - GENERATED by platform-kit/tools/make_gameuikit_3x.py from\n'
            '// parts/GameUIKit.js (core, byte for byte) + parts-3x/GameUIKit.adapter-3x.js. Do not edit this copy.\n'
            '// Copy it unchanged to assets/tiktok-platform/GameUIKit.ts. Same interface as the 2.4 file:\n'
            "//   import GameUIKit from '../tiktok-platform/GameUIKit';   (or (globalThis as any).TikTokGameUIKit)\n"
            '// @ts-nocheck\n'
            "import * as cc from 'cc';\n\n" % ver.group(1)
            + core + '\n\n' + adapter.rstrip('\n') + '\n\n'
            'const GameUIKit = createGameUIKit(makeGameUIAdapter3x(cc));\n'
            '(globalThis as any).TikTokGameUIKit = GameUIKit;\n'
            'export { GameUIKit };\n'
            'export default GameUIKit;\n')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        same = OUT.is_file() and OUT.read_text(encoding='utf-8') == text
        print('parts-3x/GameUIKit.ts ' + ('is current' if same else 'is stale: run tools/make_gameuikit_3x.py'))
        return 0 if same else 1
    OUT.write_text(text, encoding='utf-8')
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
