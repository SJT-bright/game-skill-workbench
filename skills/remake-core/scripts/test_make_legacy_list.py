#!/usr/bin/env python3
"""make_legacy_list.py v2 (v7.7 W-L), synthetic folders only.

  - the same game in two folders (J and a P version folder) is one entry with both folders and keeps its unique uuids;
  - two games built from one starter pack do not merge, and the starter uuids are not stored;
  - an empty game folder is dropped, a '待-X' folder is the same game as 'X';
  - a project-root build whose uuids are all generated joins its source by game name;
  - the written JSON works with policy.decide(): both games legacy, the starter pack new.
Run: python3 test_make_legacy_list.py   (KIROCREW_SCRATCH, when set, holds the temporary folders)
"""
import json
import os
import shutil
import sys
import tempfile
import unittest
import uuid as uuidlib
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_legacy_list as M  # noqa: E402
from tiktok_finalize_steps import policy as P  # noqa: E402


def uids(n, seed):
    return [str(uuidlib.uuid5(uuidlib.NAMESPACE_DNS, '%s-%d' % (seed, i))) for i in range(n)]


def project(path, scenes, assets):
    """A Cocos 2.4 project: assets/*.meta with the given uuids (scenes get .fire.meta)."""
    (path / 'assets').mkdir(parents=True, exist_ok=True)
    (path / 'project.json').write_text(json.dumps({'engine': 'cocos-creator-js', 'version': '2.4.15'}))
    for i, u in enumerate(scenes):
        (path / 'assets' / ('s%d.fire.meta' % i)).write_text(json.dumps({'uuid': u, 'importer': 'scene'}))
    for i, u in enumerate(assets):
        (path / 'assets' / ('a%d.png.meta' % i)).write_text(json.dumps({'uuid': u, 'importer': 'texture'}))
    return path


def native_zip(path, scenes, assets):
    """A TikTok upload ZIP: game.js + game.json + project.config.json and one bundle config."""
    path.parent.mkdir(parents=True, exist_ok=True)
    all_u = list(scenes) + list(assets)
    cfg = {'uuids': all_u, 'scenes': {'db://assets/s%d.fire' % i: i for i in range(len(scenes))}}
    with zipfile.ZipFile(path, 'w') as z:
        for n in ('game.js', 'game.json', 'project.config.json'):
            z.writestr(n, '{}')
        z.writestr('assets/main/config.json', json.dumps(cfg))
        z.writestr('cocos2d-js-min.js', '')
    return path


class LegacyListV2(unittest.TestCase):
    def setUp(self):
        base = os.environ.get('KIROCREW_SCRATCH') or None
        self.root = Path(tempfile.mkdtemp(prefix='wl-test-', dir=base))
        self.addCleanup(shutil.rmtree, self.root, True)
        r = self.root
        self.J, self.D, self.Pr, self.T = r / 'J', r / 'D', r / 'P', r / 'T'
        for d in (self.J, self.D, self.Pr / 'exports', self.T / 'projects'):
            d.mkdir(parents=True)
        self.starter = uids(60, 'starter')                       # one starter pack, copied into two packs
        project(self.T / 'projects' / 'pack-a' / 'proj', uids(1, 'starter-scene'), self.starter)
        project(self.T / 'projects' / 'pack-b' / 'proj', uids(1, 'starter-scene'), self.starter)
        self.a_scene, self.a_art = uids(1, 'a-scene'), uids(80, 'a-art')
        self.b_scene, self.b_art = uids(1, 'b-scene'), uids(70, 'b-art')
        # game A: J folder (source) + a P version folder (an older copy) -> one game
        project(self.J / '1someone-Alpha（自制）' / 'proj', self.a_scene, self.starter + self.a_art)
        project(self.Pr / 'exports' / 'Alpha-v3-20261020' / 'proj', self.a_scene, self.starter + self.a_art[:60])
        # game B: same starter pack, its own art; its 待- twin holds the TikTok package
        project(self.J / '1other-Bravo（自制）' / 'proj', self.b_scene, self.starter + self.b_art)
        native_zip(self.J / '待-1other-Bravo（自制）' / 'Bravo_TikTok.zip', self.b_scene, self.b_art[:50])
        # an empty game folder
        (self.J / '1nobody-Empty（自制）').mkdir()
        # game C only under P: source, and a build whose uuids are all generated by the editor
        self.c_scene, self.c_art = uids(1, 'c-scene'), uids(40, 'c-art')
        project(self.Pr / 'exports' / 'Charlie-Duo-v19-Cocos-Source-20261029' / 'src', self.c_scene, self.c_art)
        native_zip(self.Pr / 'exports' / 'Charlie-Duo-v13-Native-Test-20261023' / 'Charlie.zip', [], uids(30, 'c-gen'))

    def run_list(self):
        entries, stats, extra = M.build(delivered=[self.J], project_roots=[self.Pr], templates=[self.T],
                                        log=lambda m: None, project_dirs=('exports',))
        out = self.root / 'LEGACY_GAMES.json'
        M.write_json(entries, stats, out)
        M.write_review(entries, stats, self.root / 'review.md', out, extra['check'])
        return entries, stats, extra, P.load_legacy(out)

    def entry(self, entries, folder):
        hit = [e for e in entries if folder in e['folders']]
        self.assertEqual(len(hit), 1, (folder, [e['folders'] for e in entries]))
        return hit[0]

    def test_same_game_in_two_folders_keeps_unique_uuids(self):
        entries, _, _, legacy = self.run_list()
        a = self.entry(entries, 'J/1someone-Alpha（自制）')
        self.assertIn('P/exports/Alpha-v3-20261020', a['folders'])
        self.assertEqual(a['scene_uuids'], self.a_scene)            # draft v1 dropped it: found in two "games"
        self.assertEqual(a['asset_uuids_total'], 80)
        old = P.decide(uuids=self.a_scene, assets=self.a_art[:60], legacy=legacy)
        self.assertEqual((old['policy'], old['legacy_match'][0]['folder']), ('legacy', 'J/1someone-Alpha（自制）'))

    def test_two_games_from_one_starter_pack_do_not_merge(self):
        entries, stats, _, legacy = self.run_list()
        a = self.entry(entries, 'J/1someone-Alpha（自制）')
        b = self.entry(entries, 'J/1other-Bravo（自制）')
        self.assertIsNot(a, b)
        stored = set(a['asset_uuids']) | set(b['asset_uuids']) | set(a['scene_uuids']) | set(b['scene_uuids'])
        self.assertFalse(stored & set(self.starter))
        self.assertEqual(b['scene_uuids'], self.b_scene)
        starter = P.decide(uuids=uids(1, 'starter-scene'), assets=self.starter, legacy=legacy)
        self.assertEqual(starter['policy'], 'new')
        self.assertEqual(P.decide(uuids=[], assets=self.b_art[:50], legacy=legacy)['policy'], 'legacy')

    def test_empty_folder_dropped_and_wait_twin_merged(self):
        entries, stats, _, _ = self.run_list()
        self.assertFalse([e for e in entries if any('Empty' in f for f in e['folders'])])
        self.assertIn('J/1nobody-Empty（自制）', stats['units_without_packages'])
        b = self.entry(entries, 'J/1other-Bravo（自制）')
        self.assertIn('J/待-1other-Bravo（自制）', b['folders'])

    def test_project_root_build_joins_its_source_by_name(self):
        entries, _, extra, _ = self.run_list()
        c = self.entry(entries, 'P/exports/Charlie-Duo-v19-Cocos-Source-20261029')
        self.assertIn('P/exports/Charlie-Duo-v13-Native-Test-20261023', c['folders'])
        self.assertEqual(extra['check']['not_recognised'], [])
        self.assertEqual(len(entries), 3)

    def test_link_threshold(self):
        own = [set(uids(100, 'x')), set(uids(95, 'x')), set(uids(10, 'x')) | set(uids(90, 'y'))]
        nodes = [{'kind': 'source', 'scenes': set(), 'assets': o, 'unit': 'P/w/%d' % i, 'where': 'P', 'forced': None}
                 for i, o in enumerate(own)]
        groups, _, links = M.cluster(nodes, set())
        self.assertIn([0, 1], groups)                  # 95 of 95 shared
        self.assertIn([2], groups)                     # 10 of 100 shared: another game built on it, not merged


if __name__ == '__main__':
    unittest.main(verbosity=1)
